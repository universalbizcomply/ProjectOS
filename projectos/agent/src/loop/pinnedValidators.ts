/**
 * A PHASE'S VALIDATORS JUDGE IT FROM THE APPROVED COMMIT — PROJECTOS-FINISH-WRITEPATHS1A.
 *
 * WHY. A phase's approved `writePaths` may name a validator file: a phase that adds a rule has to edit
 * the validator that pins it. Those validators are also what the loop runs to judge the phase. Run from
 * the working tree, a worker could weaken the very check that decides whether its work passes — and the
 * check would still report a pass for the rule the owner approved.
 *
 * WHAT IS PINNED. The CODE under `projectos/validators/`: every `.js`, `.cjs` and `.json` file there is
 * compiled from the phase's BASE commit — the commit the brief was bound to, before any worker ran —
 * whatever the working tree now holds at that path. Any other code extension a loader is registered for
 * under that directory refuses to load. The DATA a validator reads is not pinned: a validator judges the
 * worker's tree, which is its job.
 *
 * WHAT IS NOT PINNED, stated rather than implied. Code a validator loads from elsewhere in the repository
 * (`projectos/security/`, `projectos/worker/`…) and schemas it reads as data are loaded as the worker
 * left them, and code loaded in-process can in principle undo the loader. The pin removes the direct
 * route — rewriting the validator itself — not every indirect one; those stay visible in the diff the
 * reviewer and the owner judge.
 *
 * HOW. The base commit's validator files are written to a fresh directory outside the checkout, and the
 * validator runs under a `--require` loader that compiles the pinned copy in place of the file on disk,
 * keeping the real filename, so every `__dirname`-relative repository root still resolves to the
 * governed checkout. The loader passes itself to any child Node process through `NODE_OPTIONS`.
 *
 * WHAT FAILS CLOSED. A base commit that is not a full object name, a tree git cannot list, a blob git
 * cannot show or write, a required validator absent from the base commit: each makes the validator
 * UNRUNNABLE, and an unrunnable check has not passed. A validator file the worker deleted fails to
 * resolve. Validator code the loader cannot place under the governed root — the root reached through a
 * junction or link, which Node resolves and a plain prefix would not match — REFUSES to load rather
 * than falling through to the working tree's copy, and so does an entry script that was not pinned.
 *
 * THE LOOP'S OWN ENFORCEMENT CODE is the built runtime this process loaded before any worker started.
 * It is git-ignored build output: never grantable (see `writePathGrants`), and new ignored content under
 * a grant stops the run. A worker edit to enforcement SOURCE changes nothing this run executes.
 */
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import type { System } from '../system.js';

/** The repository directory whose code is pinned. */
export const PINNED_VALIDATOR_ROOT = 'projectos/validators';

/** The files under it that are compiled, and so pinned. Data files there are read as the worker left them. */
const PINNED_CODE = /\.(?:js|cjs|json)$/i;

export type ValidatorPin =
  | { readonly ok: true; readonly commit: string; readonly loader: string; readonly files: ReadonlySet<string>; readonly dir: string }
  | { readonly ok: false; readonly commit: string; readonly problem: string };

/** The loader, as text. Generated per pin so nothing it trusts is read from the governed checkout. */
export function pinnedLoaderSource(root: string, treeDir: string): string {
  const cfg = JSON.stringify({ root, dir: treeDir, prefix: `${PINNED_VALIDATOR_ROOT}/` });
  return `"use strict";
// Generated by ProjectOS (pinnedValidators.ts). Compiles projectos/validators code from the phase's base commit.
const Module = require("module");
const fs = require("fs");
const path = require("path");
const CFG = ${cfg};
const ROOTS = [path.resolve(CFG.root)];
try { ROOTS.push(fs.realpathSync.native(CFG.root)); } catch (_) {}
const PREFIXES = ROOTS.map((r) => r.toLowerCase() + path.sep);
const self = __filename;
const opt = "--require " + JSON.stringify(self);
if (!String(process.env.NODE_OPTIONS || "").includes(opt)) {
  process.env.NODE_OPTIONS = (process.env.NODE_OPTIONS ? process.env.NODE_OPTIONS + " " : "") + opt;
}
function relUnderRoot(abs) {
  const low = abs.toLowerCase();
  for (const p of PREFIXES) if (low.startsWith(p)) return abs.slice(p.length).split(path.sep).join("/");
  return null;
}
function pinnedPath(filename) {
  const abs = path.resolve(filename);
  const rel = relUnderRoot(abs);
  if (rel === null) {
    if (/[\\\\/]projectos[\\\\/]validators[\\\\/]/i.test(abs)) {
      throw new Error("ProjectOS: " + abs + " is validator code outside the governed root as the pin knows it, so it is not loaded");
    }
    return null;
  }
  if (!rel.toLowerCase().startsWith(CFG.prefix)) return null;
  const p = path.join(CFG.dir, ...rel.split("/"));
  if (!fs.existsSync(p)) throw new Error("ProjectOS: " + rel + " is not in the phase's base commit, so it cannot judge this phase");
  return p;
}
const js = Module._extensions[".js"];
const json = Module._extensions[".json"];
Module._extensions[".js"] = function (module, filename) {
  const p = pinnedPath(filename);
  if (p === null) {
    if (module.id === ".") throw new Error("ProjectOS: the validator entry " + filename + " could not be pinned, so it is not run");
    return js(module, filename);
  }
  module._compile(fs.readFileSync(p, "utf8").replace(/^#!.*/, ""), filename);
};
Module._extensions[".json"] = function (module, filename) {
  const p = pinnedPath(filename);
  if (p === null) return json(module, filename);
  module.exports = JSON.parse(fs.readFileSync(p, "utf8").replace(/^\\uFEFF/, ""));
};
for (const ext of Object.keys(Module._extensions)) {
  if (ext === ".js" || ext === ".json") continue;
  const original = Module._extensions[ext];
  Module._extensions[ext] = function (module, filename) {
    const rel = relUnderRoot(path.resolve(filename));
    if (rel !== null && rel.toLowerCase().startsWith(CFG.prefix)) {
      throw new Error("ProjectOS: " + rel + " is validator code the pin does not cover, so it is not loaded");
    }
    return original(module, filename);
  };
}
`;
}

/** Remove a directory this module created. Never throws. */
function removeDir(dir: string): void {
  try {
    rmSync(dir, { recursive: true, force: true });
  } catch {
    // A leftover temporary copy is untidy, never unsafe: it is never read again.
  }
}

/** Write the base commit's validator code outside the checkout, with its loader. Never throws. */
export function pinValidators(sys: System, root: string, commit: string): ValidatorPin {
  const fail = (problem: string): ValidatorPin => ({ ok: false, commit, problem });
  if (!/^[0-9a-f]{40}$/.test(commit)) return fail(`the phase's base commit '${commit}' is not a full commit id`);
  const listed = sys.exec('git', ['-C', root, 'ls-tree', '-r', '-z', '--name-only', commit, '--', PINNED_VALIDATOR_ROOT]);
  if (listed.code !== 0 || listed.failure !== undefined) return fail(`git could not list ${PINNED_VALIDATOR_ROOT} at the base commit ${commit.slice(0, 12)}`);
  const rels = listed.stdout.split('\0').filter((r) => r !== '' && PINNED_CODE.test(r));
  let dir: string;
  try {
    dir = mkdtempSync(join(tmpdir(), 'projectos-pinned-'));
  } catch {
    return fail('no directory outside the checkout could be created for the pinned validators');
  }
  const treeDir = join(dir, 'tree');
  try {
    for (const rel of rels) {
      const blob = sys.exec('git', ['-C', root, 'show', `${commit}:${rel}`]);
      if (blob.code !== 0 || blob.failure !== undefined) {
        removeDir(dir);
        return fail(`git could not show ${rel} at the base commit ${commit.slice(0, 12)}`);
      }
      sys.writeText(join(treeDir, ...rel.split('/')), blob.stdout);
    }
    const loader = join(dir, 'pinned-loader.cjs');
    sys.writeText(loader, pinnedLoaderSource(root, treeDir));
    return { ok: true, commit, loader, files: new Set(rels), dir };
  } catch {
    removeDir(dir);
    return fail('the pinned validators could not be written outside the checkout');
  }
}

/** Remove a pin's directory. Never throws. */
export function releasePin(pin: ValidatorPin): void {
  if (pin.ok) removeDir(pin.dir);
}

/** Pin, run, release — the only way the loop and closure preparation run a phase's validators. */
export function withPinnedValidators<T>(sys: System, root: string, commit: string, use: (pin: ValidatorPin) => T): T {
  const pin = pinValidators(sys, root, commit);
  try {
    return use(pin);
  } finally {
    releasePin(pin);
  }
}
