"use strict";
// ProjectOS Watchdog — build the outer sentinel repository contents (P3).
//
//   node projectos/scripts/watchdog-sentinel-package.cjs --core-tag watchdog-core/v0.1.0 \
//        --sources projectos/watchdog/sentinel/registry/sources.json --out <dir> [--schedule "17 * * * *"]
//   node projectos/scripts/watchdog-sentinel-package.cjs --verify <dir>
//
// Writes into <dir> (the working copy of the private sentinel repository):
//   core/src/*.ts                         Watchdog Core, read from the TAGGED commit (never the working tree)
//   sentinel/run-sentinel.ts              runner, read from ProjectOS HEAD (must be committed)
//   sentinel/registry.json                generated registry stamped with ProjectOS HEAD
//   .github/workflows/watchdog-sentinel.yml
//   package.json, README.md
//   sentinel.lock.json                    core tag + commit, runner commit, sha256 of every file above
//
// It never commits, pushes, dispatches or schedules anything itself. The schedule
// is written only when --schedule is given, and only one of the two cadences the
// Owner approved (budget gate); otherwise the workflow is manual-dispatch only.

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { execFileSync } = require("child_process");
const lib = require("./_watchdog-lib.cjs");
const { generate } = require("./watchdog-sentinel-registry.cjs");

const ALLOWED_SCHEDULES = ["17,47 * * * *", "17 * * * *"];
const LOCK = "sentinel.lock.json";

const git = (...args) => execFileSync("git", args, { encoding: "utf8", maxBuffer: 16 * 1024 * 1024 });
const sha256 = (text) => crypto.createHash("sha256").update(text, "utf8").digest("hex");

function workflowFrom(template, schedule) {
  const body = template.replace(/^#[^\n]*\n(#[^\n]*\n|\n)*/, "");
  const header = [
    "# ProjectOS Watchdog — outer sentinel (GENERATED by projectos/scripts/watchdog-sentinel-package.cjs).",
    "# Do not edit here: change the canonical source in universalbizcomply/ProjectOS and re-package.",
    "# One job, sequential public read-only probes, no matrix. No paid Actions overage is authorised.",
    "",
  ].join("\n");
  let wf = header + body;
  const commented = /  # schedule:\n  #   - cron: "[^"]*"\n/;
  if (!commented.test(wf)) throw new Error("workflow template has no commented schedule block");
  if (schedule) {
    if (!ALLOWED_SCHEDULES.includes(schedule)) throw new Error("schedule must be one of " + ALLOWED_SCHEDULES.join(" | "));
    wf = wf.replace(commented, '  schedule:\n    - cron: "' + schedule + '"\n');
  } else {
    wf = wf.replace(commented, "");
  }
  return wf;
}

function build(opts) {
  const top = git("rev-parse", "--show-toplevel").trim();
  const head = git("rev-parse", "HEAD").trim();
  const dirty = git("status", "--porcelain", "--", "projectos/watchdog/sentinel", "projectos/scripts").trim();
  if (dirty) throw new Error("sentinel sources are not committed; commit first so the lock names real commits:\n" + dirty);
  const coreCommit = git("rev-list", "-n", "1", opts.coreTag).trim();
  const coreVersion = JSON.parse(git("show", coreCommit + ":projectos/watchdog/core/package.json")).version;
  const tagVersion = opts.coreTag.replace(/^watchdog-core\/v/, "");
  if (coreVersion !== tagVersion) throw new Error("tag " + opts.coreTag + " carries core " + coreVersion);

  const files = {};
  for (const name of git("ls-tree", "--name-only", coreCommit + ":projectos/watchdog/core/src").split("\n").filter(Boolean)) {
    if (!name.endsWith(".ts")) continue;
    files["core/src/" + name] = git("show", coreCommit + ":projectos/watchdog/core/src/" + name);
  }
  files["sentinel/run-sentinel.ts"] = git("show", head + ":projectos/watchdog/sentinel/run-sentinel.ts");
  const template = git("show", head + ":projectos/watchdog/sentinel/workflow.template.yml");
  files[".github/workflows/watchdog-sentinel.yml"] = workflowFrom(template, opts.schedule || null);
  const registry = generate(path.resolve(opts.sources), head);
  files["sentinel/registry.json"] = lib.canonicalJson(registry);
  files["package.json"] = lib.canonicalJson({ name: "projectos-watchdog-sentinel", private: true, type: "module", license: "UNLICENSED" });
  files["README.md"] = [
    "# ProjectOS Watchdog — outer sentinel",
    "",
    "Generated from `universalbizcomply/ProjectOS` (`projectos/watchdog/sentinel/`). Do not edit by hand:",
    "change the canonical source, re-run `projectos/scripts/watchdog-sentinel-package.cjs`, review the diff, commit.",
    "",
    "- Public, read-only probes of each registered product (GET only; nothing is written to any product).",
    "- Cannot advance any product's sentinel liveness (unauthenticated).",
    "- One deduplicated issue per project / environment / check class; closed only on explicit PASS.",
    "- `sentinel.lock.json` pins Watchdog Core `" + opts.coreTag + "` and the runner/registry commit.",
    "",
  ].join("\n");

  const lock = {
    lock_version: 1,
    core_tag: opts.coreTag,
    core_commit: coreCommit,
    core_version: coreVersion,
    runner_source_commit: head,
    registry_sha256: registry.content_sha256,
    schedule: opts.schedule || null,
    files: Object.fromEntries(Object.keys(files).sort().map((k) => [k, sha256(files[k])])),
  };
  const out = path.resolve(opts.out);
  for (const [rel, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(out, rel)), { recursive: true });
    fs.writeFileSync(path.join(out, rel), text, "utf8");
  }
  fs.writeFileSync(path.join(out, LOCK), lib.canonicalJson(lock), "utf8");
  return { lock, top };
}

function verify(dir) {
  const errors = [];
  const lock = lib.readJson(path.join(dir, LOCK));
  for (const [rel, want] of Object.entries(lock.files || {})) {
    const p = path.join(dir, rel);
    if (!fs.existsSync(p)) { errors.push("missing " + rel); continue; }
    if (sha256(fs.readFileSync(p, "utf8")) !== want) errors.push("modified " + rel);
  }
  const reg = lib.readJson(path.join(dir, "sentinel/registry.json"));
  for (const e of lib.registryErrors(reg)) errors.push("registry: " + e);
  if (reg.content_sha256 !== lock.registry_sha256) errors.push("registry does not match lock");
  const wf = fs.readFileSync(path.join(dir, ".github/workflows/watchdog-sentinel.yml"), "utf8");
  const crons = [...wf.matchAll(/^\s*-\s*cron:\s*"([^"]*)"/gm)].map((m) => m[1]);
  for (const c of crons) if (!ALLOWED_SCHEDULES.includes(c)) errors.push("unapproved schedule " + c);
  if (/strategy\s*:|matrix\s*:/.test(wf)) errors.push("workflow must not use a matrix");
  return errors;
}

function main() {
  const argv = process.argv.slice(2);
  const get = (k) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : undefined; };
  try {
    if (get("--verify")) {
      const errors = verify(get("--verify"));
      if (errors.length) { errors.forEach((e) => console.error("FAIL: " + e)); process.exit(1); }
      console.log("watchdog-sentinel-package --verify: PASS");
      return;
    }
    for (const k of ["--core-tag", "--sources", "--out"]) if (!get(k)) throw new Error(k + " is required");
    const { lock } = build({ coreTag: get("--core-tag"), sources: get("--sources"), out: get("--out"), schedule: get("--schedule") });
    console.log("watchdog-sentinel-package: core " + lock.core_version + " @ " + lock.core_commit.slice(0, 7) + ", runner @ " +
      lock.runner_source_commit.slice(0, 7) + ", registry " + lock.registry_sha256.slice(0, 12) + ", schedule " + (lock.schedule || "none (manual dispatch only)"));
  } catch (e) {
    console.error("watchdog-sentinel-package: " + e.message);
    process.exit(1);
  }
}

if (require.main === module) main();
module.exports = { build, verify, workflowFrom, ALLOWED_SCHEDULES };
