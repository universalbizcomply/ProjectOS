  L.push("- **Status:** " + f(req.status));
  L.push("- **Branch:** " + f(req.branch));
  L.push("- **Commit:** " + f(req.commit));
  L.push("- **Report date:** " + f(req.reportDate));
  L.push("- **Generated by:** " + f(req.generatedBy, "projectos/scripts/create-phase-report.cjs") + " (local-only; not an approval)");
  L.push("");
  L.push("## Files changed"); L.push(list(req.filesChanged));
  L.push(""); L.push("## Scope"); L.push(f(req.scope));
  L.push(""); L.push("## Forbidden actions checked"); L.push(list(req.forbiddenActionsChecked));
  L.push(""); L.push("## Validators"); L.push(list(req.validators));
  L.push(""); L.push("## tsc / build / eslint"); L.push(f(req.buildLintTypecheck, "N/A"));
  L.push(""); L.push("## Security review"); L.push(f(rv.securityReview, "N/A"));
  L.push(""); L.push("## Code review"); L.push(f(rv.codeReview, "N/A"));
  L.push(""); L.push("## Database review"); L.push(f(rv.databaseReview, "N/A"));
  L.push(""); L.push("## Staging proof"); L.push(f(req.stagingProof, "N/A"));
  L.push(""); L.push("## Production touched?"); L.push(yn(req.productionTouched));
  L.push(""); L.push("## Database touched?"); L.push(yn(req.databaseTouched));
  L.push(""); L.push("## External sends / payments?"); L.push(yn(req.externalSendsPayments));
  L.push(""); L.push("## Residue"); L.push(f(req.residue, "NONE"));
  L.push(""); L.push("## Risks"); L.push(list(req.risks, "none"));
