"use strict";
const fs = require("fs");
const path = require("path");
const ROOT = path.resolve(__dirname, "..", "..");
const STATUSES = [
  "IMPLEMENTED LOCALLY / AWAITING OWNER-ADVISOR REVIEW",
  "BLOCKED", "DO NOT CLOSE", "ACCEPTED FOR CLOSURE", "CLOSED"
];
function within(p) { const a = path.resolve(p); return a === ROOT || a.indexOf(ROOT + path.sep) === 0; }
function rel(p) { return path.relative(ROOT, p).replace(/\\/g, "/"); }
function parseArgs(argv) {
  const f = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.indexOf("--") === 0) {
      const k = a.slice(2);
      const n = argv[i + 1];
      if (n === undefined || n.indexOf("--") === 0) { f[k] = true; } else { f[k] = n; i++; }
    }
  }
  return f;
}
function loadRequest(flags) {
  let req = {};
  if (flags.input) {
    const p = path.resolve(flags.input);
    if (!within(p)) throw new Error("input path outside ProjectOS");
    req = JSON.parse(fs.readFileSync(p, "utf8").replace(/^﻿/, ""));
  }
  const scalar = ["project", "phase", "phaseType", "status", "branch", "commit", "scope", "decisionNeeded", "reportDate", "outputPath", "generatedBy", "sourceLimitations", "stagingProof", "residue", "buildLintTypecheck"];
  scalar.forEach(function (k) { if (typeof flags[k] === "string") req[k] = flags[k]; });
  if (typeof flags.out === "string") req.outputPath = flags.out;
  return req;
}
function guardOut(outPath) {
  if (!outPath) throw new Error("no output path (--out or outputPath in request)");
  const a = path.resolve(ROOT, outPath);
  if (!within(a)) throw new Error("refusing output outside C:\\dev\\ProjectOS: " + a);
  return a;
}
function ensureDir(file) { fs.mkdirSync(path.dirname(file), { recursive: true }); }
function f(v, fb) { if (v === undefined || v === null || v === "") return fb || "NEEDS SOURCE"; return String(v); }
function list(a, fb) {
  if (!Array.isArray(a) || a.length === 0) return "- " + (fb || "NEEDS SOURCE");
  return a.map(function (x) { return "- " + x; }).join("\n");
}
function yn(b) { if (b === true) return "yes"; if (b === false) return "no"; return "NOT VERIFIED"; }
function eccBlock(reviews) {
  const rv = reviews || {};
  return [
    "## ECC review sections (evidence only — recommendation is not approval)",
    "- **Code Review:** " + f(rv.codeReview, "N/A"),
    "- **Security Review:** " + f(rv.securityReview, "N/A"),
    "- **Database Review:** " + f(rv.databaseReview, "N/A"),
    "- **Build/Lint/Typecheck Review:** " + f(rv.buildLintTypecheckReview, "N/A"),
    "- **Test Review:** " + f(rv.testReview, "N/A"),
    "- **Quality Gate Review:** " + f(rv.qualityGateReview, "N/A"),
    "- **Silent Failure Review:** " + f(rv.silentFailureReview, "N/A"),
    "- **Review Scope / Limitations:** " + f(rv.reviewScopeLimitations, "N/A"),
    "- **External Tools Used:** " + yn(rv.externalToolsUsed),
    "- **MCP Used:** " + yn(rv.mcpUsed),
    "- **Owner Approval Required:** " + f(rv.ownerApprovalRequired, "NOT VERIFIED")
  ].join("\n");
}
