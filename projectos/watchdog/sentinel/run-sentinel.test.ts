import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadRegistry, main, probeEntry, parseIssue, issueMarker } from "./run-sentinel.ts";
import type { RegistryEntry, SentinelIssue } from "../core/src/index.ts";

const EXAMPLE = readFileSync(fileURLToPath(new URL("./example/registry.example.json", import.meta.url)), "utf8");

test("registry generated by the ProjectOS (CommonJS) generator verifies in the sentinel runtime", async () => {
  const entries = await loadRegistry(EXAMPLE);
  assert.equal(entries.length, 1);
  const tampered = EXAMPLE.replace("https://example.com", "https://evil.example.com");
  await assert.rejects(loadRegistry(tampered), /content hash mismatch/);
});

const entry: RegistryEntry = {
  project: "demo", environment: "production", public_url: "https://demo.example.com", health_path: "/health",
  expected_service: "demo", expected_release: null, timeout_ms: 2000, check_classes: ["reachability", "https", "health", "release_identity"],
};

function fakeFetch(routes: Record<string, () => Response | Promise<Response>>, seen: string[] = []): typeof fetch {
  return (async (input: RequestInfo | URL, init?: RequestInit) => {
    const url = String(input);
    seen.push((init?.method ?? "GET") + " " + url);
    for (const [prefix, fn] of Object.entries(routes)) if (url.startsWith(prefix)) return await fn();
    throw new TypeError("fetch failed");
  }) as typeof fetch;
}

test("probe: healthy product", async () => {
  const f = fakeFetch({
    "https://demo.example.com/health": () => Response.json({ status: "ok", service: "demo", environment: "production", release: "0123456", watchdog: "0.1.0" }),
    "https://demo.example.com": () => new Response("ok"),
  });
  const out = await probeEntry(entry, f);
  assert.deepEqual(out.map((o) => o.check_class + ":" + o.status).sort(), ["health:PASS", "https:PASS", "reachability:PASS", "release_identity:PASS"]);
});

test("probe: down product is CRITICAL; health unavailable makes release identity ERROR, not PASS", async () => {
  const out = await probeEntry(entry, fakeFetch({}));
  const by = Object.fromEntries(out.map((o) => [o.check_class, o]));
  assert.equal(by.reachability.status, "CRITICAL");
  assert.equal(by.health.status, "CRITICAL");
  assert.equal(by.release_identity.status, "ERROR");
});

test("probe: wrong service, degraded, missing release", async () => {
  const f = (body: unknown) => fakeFetch({ "https://demo.example.com/health": () => Response.json(body), "https://demo.example.com": () => new Response("") });
  assert.equal((await probeEntry(entry, f({ status: "ok", service: "other", release: "0123456" }))).find((o) => o.check_class === "health")!.code, "SERVICE_MISMATCH");
  assert.equal((await probeEntry(entry, f({ status: "degraded", service: "demo", release: "0123456" }))).find((o) => o.check_class === "health")!.status, "WARN");
  assert.equal((await probeEntry(entry, f({ status: "ok", service: "demo" }))).find((o) => o.check_class === "release_identity")!.code, "RELEASE_MISSING");
});

test("issue marker round-trips", () => {
  const i: SentinelIssue = { project: "demo", environment: "production", check_class: "health", severity: "CRITICAL", opened_at: "2026-09-21T10:17:00.000Z", last_alerted_at: "2026-09-21T10:17:00.000Z" };
  assert.deepEqual(parseIssue("text\n\n" + issueMarker(i)), i);
  assert.equal(parseIssue("no marker"), null);
});

test("main: failing product opens ONE issue and fails the workflow; next run with the issue open succeeds quietly; PASS closes", async () => {
  const reg = EXAMPLE;
  const issues: Array<{ number: number; body: string; state: string }> = [];
  const calls: string[] = [];
  let productUp = false;
  const f = (async (input: RequestInfo | URL, init?: RequestInit) => {
    const url = String(input);
    const method = init?.method ?? "GET";
    calls.push(method + " " + url);
    if (url.startsWith("https://api.github.com/repos/o/s/issues?")) return Response.json(issues.filter((i) => i.state === "open").map((i) => ({ ...i, user: { login: "github-actions[bot]" } })));
    if (url === "https://api.github.com/repos/o/s/issues" && method === "POST") {
      const b = JSON.parse(String(init!.body));
      issues.push({ number: issues.length + 1, body: b.body, state: "open" });
      return Response.json({ number: issues.length }, { status: 201 });
    }
    const m = /issues\/(\d+)(\/comments)?$/.exec(url);
    if (m && url.startsWith("https://api.github.com/")) {
      const i = issues[Number(m[1]) - 1];
      if (!m[2] && method === "PATCH") { const b = JSON.parse(String(init!.body)); if (b.state) i.state = b.state; if (b.body) i.body = b.body; }
      return Response.json({}, { status: 200 });
    }
    if (!productUp) throw new TypeError("fetch failed");
    if (url.endsWith("/health")) return Response.json({ status: "ok", service: "example-product", release: "0123456" });
    return new Response("ok");
  }) as typeof fetch;
  const env = { GITHUB_REPOSITORY: "o/s", GITHUB_TOKEN: "t", SENTINEL_REMINDER_HOURS: "6" };
  const read = async () => reg;
  const quiet = () => {};

  assert.equal(await main(env, read, f, quiet), 1);
  const opened = issues.length;
  assert.equal(opened, 4); // one per failing check class, no duplicates
  assert.equal(await main(env, read, f, quiet), 0);
  assert.equal(issues.length, opened, "no issue spam");
  productUp = true;
  assert.equal(await main(env, read, f, quiet), 0);
  assert.ok(issues.every((i) => i.state === "closed"), "explicit PASS closes every issue");
  assert.equal(calls.some((c) => !c.startsWith("GET https://example.com") && !c.includes("api.github.com")), false, "only product GETs and GitHub API calls");
  assert.equal(calls.some((c) => c.includes("example.com") && !c.startsWith("GET ")), false, "products are never written to");
});

test("main: pages all open issues, closes duplicates, isolates failing GitHub actions", async () => {
  const marker = (cls: string, n: number) => ({
    number: n, state: "open", user: { login: "github-actions[bot]" },
    body: issueMarker({ project: "example-product", environment: "production", check_class: cls as SentinelIssue["check_class"], severity: "CRITICAL", opened_at: "2026-09-21T00:00:00.000Z", last_alerted_at: "2026-09-21T00:00:00.000Z" }),
  });
  // 100 unrelated labelled issues on page 1, the real ones on page 2, plus a duplicate
  const filler = Array.from({ length: 100 }, (_, i) => ({ number: 1000 + i, state: "open", body: "unrelated" }));
  const tracked = [marker("reachability", 5), marker("reachability", 9), marker("https", 6), marker("health", 7), marker("release_identity", 8)];
  const patches: string[] = [];
  const f = (async (input: RequestInfo | URL, init?: RequestInit) => {
    const url = String(input);
    const method = init?.method ?? "GET";
    if (url.includes("/issues?")) return Response.json(/page=1$/.test(url) ? filler : /page=2$/.test(url) ? tracked : []);
    if (method === "PATCH") {
      patches.push(url.split("/issues/")[1] + " " + String(init!.body));
      if (url.endsWith("/issues/6")) return new Response("{}", { status: 502 }); // one failing call
      return Response.json({});
    }
    if (method === "POST") return Response.json({}, { status: 201 });
    if (url.endsWith("/health")) return Response.json({ status: "ok", service: "example-product", release: "0123456" });
    return new Response("ok");
  }) as typeof fetch;
  const code = await main({ GITHUB_REPOSITORY: "o/s", GITHUB_TOKEN: "t" }, async () => EXAMPLE, f, () => {});
  assert.equal(code, 1, "a failed GitHub action fails the workflow");
  assert.ok(patches.some((p) => p.startsWith("9 ") && p.includes("not_planned")), "duplicate #9 closed, oldest #5 kept");
  for (const n of ["5", "7", "8"]) assert.ok(patches.some((p) => p.startsWith(n + " ") && p.includes("closed")), "issue " + n + " still closed after #6 failed");
});

test("main: invalid reminder interval is refused explicitly; empty uses the default", async () => {
  const lines: string[] = [];
  assert.equal(await main({ GITHUB_REPOSITORY: "o/s", GITHUB_TOKEN: "t", SENTINEL_REMINDER_HOURS: "0" }, async () => EXAMPLE, fakeFetch({}), (m) => lines.push(m)), 1);
  assert.ok(lines.some((l) => l.includes("SENTINEL_REMINDER_HOURS")));
});

test("main: missing GitHub context or a tampered registry fails the workflow", async () => {
  assert.equal(await main({}, async () => EXAMPLE, fakeFetch({}), () => {}), 1);
  assert.equal(await main({ GITHUB_REPOSITORY: "o/s", GITHUB_TOKEN: "t" }, async () => EXAMPLE.replace("5000", "6000"), fakeFetch({}), () => {}), 1);
});
